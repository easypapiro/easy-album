"use client";

import { useRouter } from "next/navigation";
import { useEffect, useMemo, useRef, useState } from "react";
import { useOwnedEvent } from "@/components/account-context";
import { Check, Download, ImageIcon, Pause, Play, Plus, Sparkle } from "@/components/ui/icons";
import { BackHeader, Button, Chip, Screen, SectionLabel, Sheet, Spinner, useResetOnHide, useToast } from "@/components/ui/kit";
import { cx } from "@/components/ui/button-class";
import { RingDivider } from "@/components/ui/ornaments";
import { downloadUrl, listAllMedia, saveFile } from "@/lib/album";
import { errorMessage } from "@/lib/errors";
import { DEFAULT_DRAFT, getVideoDraft, saveVideoDraft, uploadTrack, uploadVideo } from "@/lib/events";
import { eventTitle, duration as fmtDuration, longDate, shortDate, toneFor } from "@/lib/format";
import { canRenderVideo, renderVideo, type RenderedVideo } from "@/lib/render-video";
import { planTimeline, type Tempo } from "@/lib/tempo";
import type { Media, Transition, VideoDraft } from "@/lib/types";

/** Built-in soundtracks, generated by scripts/generate-tracks.mjs (first beat at 0 s). */
const TRACKS = [
  { id: "primo-ballo", title: "Primo ballo", mood: "Pianoforte · romantica", dot: "#EAD9D0", bpm: 72 },
  { id: "giardino", title: "Giardino d'estate", mood: "Chitarra acustica · luminosa", dot: "#DDE1D3", bpm: 104 },
  { id: "gran-finale", title: "Gran finale", mood: "Archi e percussioni · festosa", dot: "#EFE3D6", bpm: 116 },
];

/** Known beat grid of a built-in track; uploaded tracks are analysed while rendering. */
function tempoFor(d: VideoDraft): Tempo | null {
  if (d.track === "custom" && d.customTrackUrl) return null;
  const t = TRACKS.find((x) => x.id === d.track) ?? TRACKS[0];
  return { bpm: t.bpm, offset: 0 };
}

function trackSrc(id: string, d: VideoDraft): string {
  if (id === "custom" && d.customTrackUrl) return d.customTrackUrl;
  return `/music/${TRACKS.some((t) => t.id === id) ? id : TRACKS[0].id}.m4a`;
}

const trackUrl = (d: VideoDraft) => trackSrc(d.track, d);

type Job =
  | { phase: "prepare" | "record"; progress: number }
  | { phase: "upload"; progress: number; video: RenderedVideo; preview: string }
  | { phase: "done"; video: RenderedVideo; preview: string; saved: boolean }
  | { phase: "error"; message: string };

const TRANSITIONS: { id: Transition; label: string }[] = [
  { id: "fade", label: "Dissolvenza" },
  { id: "zoom", label: "Zoom lento" },
  { id: "slide", label: "Scorrimento" },
];

const ANIMATION: Record<Transition, string> = {
  fade: "animate-[fade-in_.8s_ease-out]",
  zoom: "animate-[ken-burns_2.5s_ease-out_forwards]",
  slide: "animate-[slide-in_.6s_ease-out]",
};

export default function CreaVideo() {
  const { event } = useOwnedEvent();
  const router = useRouter();
  const [draft, setDraft] = useState<VideoDraft | null>(null);
  const [scenes, setScenes] = useState<Media[]>([]);
  const [playing, setPlaying] = useState(false);
  const [index, setIndex] = useState(0);
  const [uploadingTrack, setUploadingTrack] = useState(false);
  const [job, setJob] = useState<Job | null>(null);
  const [toast, showToast] = useToast();
  const trackInput = useRef<HTMLInputElement>(null);
  const audio = useRef<HTMLAudioElement>(null);
  /** Plays a single track from the list, independently of the preview. */
  const sample = useRef<HTMLAudioElement>(null);
  const [listening, setListening] = useState<string | null>(null);
  const abort = useRef<AbortController | null>(null);
  const canvasHost = useRef<HTMLDivElement>(null);
  const canvas = useRef<HTMLCanvasElement | null>(null);
  useResetOnHide(() => {
    setPlaying(false);
    sample.current?.pause();
    setListening(null);
    abort.current?.abort();
    setJob(null);
  });

  // The canvas being recorded doubles as a live preview inside the sheet.
  const rendering = job?.phase === "prepare" || job?.phase === "record";
  useEffect(() => {
    const c = canvas.current;
    if (rendering && c && canvasHost.current && c.parentElement !== canvasHost.current) {
      canvasHost.current.appendChild(c);
    }
  }, [rendering]);

  // Free the local copy of the video once the sheet is closed.
  const preview = job && "preview" in job ? job.preview : null;
  useEffect(() => (preview ? () => URL.revokeObjectURL(preview) : undefined), [preview]);

  useEffect(() => {
    Promise.all([getVideoDraft(event.slug), listAllMedia(event.slug)])
      .then(([d, all]) => {
        const byId = new Map(all.map((m) => [m.id, m]));
        const picked = d.mediaIds.map((id) => byId.get(id)).filter((m): m is Media => Boolean(m));
        if (!picked.length) {
          router.replace(`/eventi/${event.slug}/seleziona`);
          return;
        }
        setScenes(picked);
        setDraft(d);
      })
      .catch((e) => {
        showToast(errorMessage(e));
        setDraft(DEFAULT_DRAFT);
      });
  }, [event.slug, router, showToast]);

  // Same beat-snapped scene lengths as the final video (without its title cards).
  const tempo = draft ? tempoFor(draft) : null;
  const { starts, total } = useMemo(() => {
    const plan = planTimeline(scenes, tempo);
    const at: number[] = [];
    let t = 0;
    for (const d of plan.scenes) {
      at.push(t);
      t += d;
    }
    return { starts: at, total: t };
    // tempo is rebuilt on every render: depend on its values.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [scenes, tempo?.bpm, tempo?.offset]);

  // Preview playback follows the music's clock, so cuts land on the beat.
  useEffect(() => {
    const a = audio.current;
    if (!playing || !a || scenes.length === 0) return;
    const t = setInterval(() => {
      if (a.currentTime >= total) a.currentTime = 0;
      let i = 0;
      while (i + 1 < starts.length && a.currentTime >= starts[i + 1]) i++;
      setIndex(i);
    }, 40);
    return () => clearInterval(t);
  }, [playing, scenes.length, starts, total]);

  const previewTrack = draft ? trackUrl(draft) : null;
  useEffect(() => {
    const a = audio.current;
    if (!a) return;
    if (playing) a.play().catch(() => {});
    else a.pause();
  }, [playing, previewTrack]);

  function update(p: Partial<VideoDraft>) {
    setDraft((d) => (d ? { ...d, ...p } : d));
    saveVideoDraft(event.slug, p).catch(() => {});
  }

  async function pickTrack(e: React.ChangeEvent<HTMLInputElement>) {
    const file = e.target.files?.[0];
    e.target.value = "";
    if (!file) return;
    if (file.size > 30 * 1024 * 1024) {
      showToast("Il brano deve pesare meno di 30 MB");
      return;
    }
    setUploadingTrack(true);
    try {
      const { url, path } = await uploadTrack(event.slug, file);
      update({
        track: "custom",
        customTrackUrl: url,
        customTrackPath: path,
        customTrackName: file.name.replace(/\.[^.]+$/, ""),
      });
    } catch (err) {
      showToast(errorMessage(err));
    } finally {
      setUploadingTrack(false);
    }
  }

  function stopListening() {
    sample.current?.pause();
    setListening(null);
  }

  function toggleListen(id: string) {
    const a = sample.current;
    if (!a || !draft) return;
    if (listening === id) return stopListening();
    setPlaying(false);
    a.src = trackSrc(id, draft);
    a.play().catch(() => setListening(null));
    setListening(id);
  }

  function togglePreview() {
    stopListening();
    if (!playing && audio.current) audio.current.currentTime = starts[index] ?? 0;
    setPlaying((p) => !p);
  }

  function showScene(i: number) {
    if (audio.current) audio.current.currentTime = starts[i] ?? 0;
    setIndex(i);
  }

  async function generate() {
    if (!draft) return;
    stopListening();
    if (!canRenderVideo()) {
      showToast("Questo browser non può creare il video: provate con Chrome o Safari aggiornati");
      return;
    }
    setPlaying(false);
    const controller = new AbortController();
    abort.current = controller;
    const c = document.createElement("canvas");
    c.className = "block aspect-video w-full rounded-[14px] bg-sand";
    canvas.current = c;
    setJob({ phase: "prepare", progress: 0 });
    let shown = "";
    // renderVideo starts its audio before awaiting anything: keep it first.
    const rendered = renderVideo({
      canvas: c,
      scenes,
      transition: draft.transition,
      trackUrl: trackUrl(draft),
      tempo: tempoFor(draft),
      title: eventTitle(event),
      subtitle: [event.date && longDate(event.date), event.location].filter(Boolean).join(" · "),
      signal: controller.signal,
      // Called every frame: only re-render when the percentage moves.
      onProgress: (phase, progress) => {
        const key = `${phase}${Math.round(progress * 100)}`;
        if (key === shown) return;
        shown = key;
        setJob({ phase, progress });
      },
    });
    saveVideoDraft(event.slug, draft).catch(() => {});

    let video: RenderedVideo;
    try {
      video = await rendered;
    } catch (e) {
      if ((e as Error).name === "AbortError") setJob(null);
      else setJob({ phase: "error", message: errorMessage(e) });
      return;
    }
    const local = URL.createObjectURL(video.blob);
    setJob({ phase: "upload", progress: 0, video, preview: local });
    try {
      const { url, path } = await uploadVideo(event.slug, video, draft.videoPath, (progress) =>
        setJob((j) => (j?.phase === "upload" ? { ...j, progress } : j)),
      );
      setDraft((d) => (d ? { ...d, videoUrl: url, videoPath: path, videoType: video.mimeType } : d));
      setJob((j) => (j?.phase === "upload" ? { phase: "done", video, preview: local, saved: true } : j));
    } catch {
      // The video still exists locally: the couple can download it right away.
      setJob((j) => (j?.phase === "upload" ? { phase: "done", video, preview: local, saved: false } : j));
    }
  }

  function closeJob() {
    if (rendering) return;
    abort.current?.abort();
    setJob(null);
  }

  const fileName = (ext: string) => `video-ricordo-${event.slug}.${ext}`;

  if (!draft) {
    return (
      <div className="flex min-h-dvh items-center justify-center text-olive">
        <Spinner />
      </div>
    );
  }

  const current = scenes[index] ?? scenes[0];
  const elapsed = starts[index] ?? 0;
  const tracks = [
    ...TRACKS,
    ...(draft.customTrackUrl
      ? [{ id: "custom", title: draft.customTrackName ?? "Il vostro brano", mood: "Brano caricato da voi", dot: "#E4DCCF" }]
      : []),
  ];

  return (
    <Screen className="safe-bottom gap-[18px] px-4 pt-3">
      <BackHeader href={`/eventi/${event.slug}/seleziona`} label="Torna alla selezione" title="Il vostro video" />

      <section className="flex flex-col gap-2.5">
        <div className="relative flex aspect-video items-center justify-center overflow-hidden rounded-[18px] bg-sand text-placeholder">
          {current && (
            <PreviewFrame key={`${current.id}-${index}-${draft.transition}`} media={current} animation={playing ? ANIMATION[draft.transition] : ""} />
          )}
          <div className="absolute inset-x-0 bottom-0 flex items-center justify-between gap-3 bg-ink/60 px-4 py-3 text-cream">
            <span className="truncate font-serif text-[22px] italic">
              {eventTitle(event)}
              {event.date && ` · ${shortDate(event.date)}`}
            </span>
            <button
              onClick={togglePreview}
              aria-label={playing ? "Pausa anteprima" : "Riproduci anteprima"}
              className="flex size-11 shrink-0 items-center justify-center rounded-full bg-cream text-ink"
            >
              {playing ? <Pause size={18} /> : <Play size={18} />}
            </button>
          </div>
        </div>

        <div className="no-scrollbar flex gap-[3px] overflow-x-auto">
          {scenes.map((m, i) => (
            <button
              key={m.id}
              onClick={() => showScene(i)}
              aria-label={`Scena ${i + 1}`}
              aria-current={i === index}
              className={cx(
                "relative h-11 min-w-[42px] flex-1 shrink-0 overflow-hidden rounded-md",
                i === index && "outline-2 outline-offset-1 outline-ink",
              )}
              style={{ background: toneFor(m.id) }}
            >
              {(m.thumbUrl || m.type === "photo") && (
                // eslint-disable-next-line @next/next/no-img-element
                <img src={m.thumbUrl ?? m.url} alt="" loading="lazy" className="size-full object-cover" />
              )}
            </button>
          ))}
        </div>
        <div className="flex justify-between text-xs text-muted">
          <span>
            {fmtDuration(elapsed)} / {fmtDuration(total)}
          </span>
          <span>
            {scenes.length} {scenes.length === 1 ? "scena" : "scene"}
          </span>
        </div>
      </section>

      <section className="flex flex-col gap-2">
        <SectionLabel>Musica</SectionLabel>
        {tracks.map((t) => {
          const on = draft.track === t.id;
          const heard = listening === t.id;
          return (
            <div
              key={t.id}
              className={cx(
                "flex items-center gap-1 rounded-[14px] bg-white pl-1.5",
                on ? "border-2 border-olive" : "border border-line",
              )}
            >
              <button
                onClick={() => toggleListen(t.id)}
                aria-label={heard ? `Ferma ${t.title}` : `Ascolta ${t.title}`}
                aria-pressed={heard}
                className="flex size-11 shrink-0 items-center justify-center"
              >
                <span
                  className={cx(
                    "flex size-9 items-center justify-center rounded-full text-ink transition-shadow",
                    heard && "shadow-[0_0_0_2px_#5E6B4E]",
                  )}
                  style={{ background: t.dot }}
                >
                  {heard ? <Pause size={14} /> : <Play size={14} />}
                </span>
              </button>
              <button
                onClick={() => update({ track: t.id })}
                aria-pressed={on}
                className="flex min-w-0 flex-1 items-center gap-3 py-2.5 pr-3 text-left"
              >
                <span className="flex min-w-0 flex-1 flex-col">
                  <span className="truncate text-[15px] font-medium">{t.title}</span>
                  <span className="text-xs text-muted">{t.mood}</span>
                </span>
                {on && <Check size={20} className="text-olive" />}
              </button>
            </div>
          );
        })}
        <input ref={trackInput} type="file" accept="audio/mpeg,audio/mp3,audio/*" className="hidden" onChange={pickTrack} />
        <button
          onClick={() => trackInput.current?.click()}
          disabled={uploadingTrack}
          className="flex h-11 items-center justify-center gap-2 rounded-[14px] border-[1.5px] border-dashed border-dash text-sm font-medium text-olive-dark"
        >
          {uploadingTrack ? <Spinner className="size-4" /> : <Plus size={16} />}
          {draft.customTrackUrl ? "Sostituite il vostro brano (MP3)" : "Caricate il vostro brano (MP3)"}
        </button>
        {previewTrack && <audio ref={audio} src={previewTrack} loop preload="none" />}
        <audio ref={sample} preload="none" onEnded={() => setListening(null)} />
      </section>

      <section className="flex flex-col gap-2">
        <SectionLabel>Transizione</SectionLabel>
        <div className="no-scrollbar -mx-4 flex gap-2 overflow-x-auto px-4">
          {TRANSITIONS.map((t) => (
            <Chip key={t.id} active={draft.transition === t.id} onClick={() => update({ transition: t.id })}>
              {t.label}
            </Chip>
          ))}
        </div>
      </section>

      {draft.videoUrl && (
        <section className="flex flex-col gap-2">
          <SectionLabel>Il vostro ultimo video</SectionLabel>
          <video
            src={draft.videoUrl}
            controls
            playsInline
            preload="metadata"
            className="aspect-video w-full rounded-[14px] bg-ink"
          />
          <Button
            variant="outline"
            onClick={() => downloadUrl(draft.videoUrl!, fileName(draft.videoType === "video/webm" ? "webm" : "mp4"))}
          >
            <Download size={18} />
            Scarica il video
          </Button>
        </section>
      )}

      <Button size="xl" block className="mt-auto" disabled={Boolean(job)} onClick={generate}>
        <Sparkle size={20} />
        {draft.videoUrl ? "Genera un nuovo video" : "Genera video"}
      </Button>

      <Sheet open={Boolean(job)} onClose={closeJob} title={job?.phase === "done" ? "Il video è pronto" : undefined}>
        {job && job.phase !== "done" && job.phase !== "error" && (
          <div className="flex flex-col gap-3 px-1 pb-4">
            <h2 className="text-center font-serif text-[26px] font-semibold">Stiamo creando il vostro video</h2>
            <div ref={canvasHost} className={cx(job.phase === "upload" && "hidden")} />
            {job.phase === "upload" && (
              <video src={job.preview} muted playsInline autoPlay loop className="aspect-video w-full rounded-[14px] bg-ink" />
            )}
            <div className="h-2 overflow-hidden rounded-full bg-line">
              <div
                className="h-full rounded-full bg-olive transition-[width] duration-300"
                style={{ width: `${Math.round(job.progress * 100)}%` }}
              />
            </div>
            <p className="flex justify-between text-sm text-ink-2">
              <span>
                {job.phase === "prepare" ? "Preparo foto e video…" : job.phase === "record" ? "Monto il video…" : "Salvo il video…"}
              </span>
              <span className="tabular-nums">{Math.round(job.progress * 100)}%</span>
            </p>
            {rendering && (
              <>
                <p className="text-[13px] leading-normal text-muted">
                  Il video dura {fmtDuration(planTimeline(scenes, tempoFor(draft)).total)} e si crea in tempo reale: tenete aperta questa
                  pagina e lo schermo acceso fino alla fine.
                </p>
                <Button variant="outline" onClick={() => abort.current?.abort()}>
                  Annulla
                </Button>
              </>
            )}
          </div>
        )}
        {job?.phase === "done" && (
          <div className="flex flex-col gap-3 px-1 pb-4">
            <video src={job.preview} controls playsInline className="aspect-video w-full rounded-[14px] bg-ink" />
            <p className="text-[13px] leading-normal text-muted">
              {job.saved
                ? "L'abbiamo salvato nella vostra area: lo ritrovate sempre in questa pagina."
                : "Non siamo riusciti a salvarlo online: scaricatelo adesso per non perderlo."}
            </p>
            <Button block onClick={() => saveFile(job.video.blob, fileName(job.video.ext)).catch(() => {})}>
              <Download size={18} />
              Scarica il video
            </Button>
            <Button block variant="outline" onClick={closeJob}>
              Chiudi
            </Button>
          </div>
        )}
        {job?.phase === "error" && (
          <div className="flex flex-col items-center gap-3 px-2 pt-2 pb-4 text-center">
            <RingDivider />
            <h2 className="font-serif text-[28px] font-semibold">Il video non è riuscito</h2>
            <p className="text-[15px] leading-normal text-ink-2">{job.message}</p>
            <Button block className="mt-2" onClick={closeJob}>
              Va bene
            </Button>
          </div>
        )}
      </Sheet>
      {toast}
    </Screen>
  );
}

function PreviewFrame({ media, animation }: { media: Media; animation: string }) {
  const src = media.type === "photo" ? media.url : media.thumbUrl;
  if (!src) return <ImageIcon size={56} strokeWidth={1} />;
  return (
    // eslint-disable-next-line @next/next/no-img-element
    <img
      src={src}
      alt=""
      className={cx("absolute inset-0 size-full object-cover", animation)}
      style={media.thumbUrl ? { backgroundImage: `url(${media.thumbUrl})`, backgroundSize: "cover" } : undefined}
    />
  );
}
